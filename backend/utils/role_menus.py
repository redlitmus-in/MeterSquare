# API endpoints behind each menu ("METHOD <flask url rule>"), traced from each page's
# services. Keys ending in ".dashboard" are the always-allowed dashboard's endpoints.
_API_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'role_menu_api.json')
try:
    with open(_API_FILE, encoding='utf-8') as fh:
        MENU_API = json.load(fh)
except (OSError, ValueError) as _e:
    log.error(f"role_menus: could not load {_API_FILE} ({_e}); menu-limited grants get only session endpoints")
    MENU_API = {}

# Session and layout endpoints every page needs; always open, even without the map
SESSION_API = frozenset({
    'GET /api/self', 'POST /api/logout', 'POST /api/user_status', 'GET /api/user_status',
    'GET /api/role-access/my-roles', 'POST /api/role-access/switch',
    'GET /api/assistant/status', 'POST /api/assistant/chat', 'PUT /api/profile',
})
# Personal pages every user has outside the sidebar (notifications, Ask AI, own support tickets)
SESSION_PREFIXES = ('/api/notifications', '/api/assistant/', '/api/support/public/', '/api/support/<')


def _norm(role_name):
    return (role_name or '').lower().replace(' ', '').replace('_', '').replace('-', '')


def menus_for_role(role_name):
    """[{'key', 'label', 'group'}] for the role, or [] when the role has no selectable menus."""
    return [{'key': m['key'], 'label': m['label'], 'group': m['group']} for m in ROLE_MENUS.get(_norm(role_name), [])]


def clean_selection(role_name, keys):
    """
    Validate a menu selection for the role.
    Returns (keys_or_None, error). None means the whole role (nothing chosen, or every menu chosen).
    """
    if keys is None:
        return None, None
    if not isinstance(keys, list) or not all(isinstance(k, str) for k in keys):
        return None, 'allowed_menus must be a list of menu keys'
    menus = ROLE_MENUS.get(_norm(role_name), [])
    valid = [m['key'] for m in menus]
    unknown = [k for k in keys if k not in valid]
    if unknown:
        return None, f"Unknown menu for this role: {', '.join(unknown)}"
    chosen = [k for k in valid if k in set(keys)]  # sidebar order, no repeats
    if not chosen:
        return None, 'Choose at least one menu'
    if len(chosen) == len(valid):
        return None, None
    return chosen, None


def menu_labels(role_name, keys):
    by_key = {m['key']: m for m in ROLE_MENUS.get(_norm(role_name), [])}
    return [(f"{by_key[k]['group']} › " if by_key[k]['group'] else '') + by_key[k]['label'] for k in keys or [] if k in by_key]


def _split(role_name, allowed):
    menus = ROLE_MENUS.get(_norm(role_name), [])
    allowed = set(allowed or [])
    return [m for m in menus if m['key'] in allowed], [m for m in menus if m['key'] not in allowed]


def blocked_routes(role_name, allowed):
    """Frontend base paths of the menus this grant does not include."""
    if not allowed:
        return []
    kept, dropped = _split(role_name, allowed)
    kept_routes = {r for m in kept for r in m['routes']}
    return sorted({r for m in dropped for r in m['routes'] if r not in kept_routes})


def allowed_api(role_name, allowed):
    """Endpoints a grant limited to `allowed` menus may call: those menus, the dashboard, session/layout."""
    return _allowed_api(_norm(role_name), tuple(sorted(allowed or [])))


@lru_cache(maxsize=256)
def _allowed_api(role_n, allowed):
    kept, _dropped = _split(role_n, allowed)
    prefix = (ROLE_MENUS.get(role_n) or [{'key': ''}])[0]['key'].split('.')[0]
    api = set(SESSION_API) | set(MENU_API.get('_always_open', [])) | set(MENU_API.get(f'{prefix}.dashboard', []))
    for m in kept:
        api |= set(MENU_API.get(m['key'], []))
    return frozenset(api)


def blocked_api(role_name, allowed):
    """Mapped endpoints of the role's other menus that this grant cannot call (for display and tests)."""
    if not allowed:
        return frozenset()
    _kept, dropped = _split(role_name, allowed)
    ok = allowed_api(role_name, allowed)
    return frozenset(a for m in dropped for a in MENU_API.get(m['key'], []) if a not in ok)


def menu_block_message(grant, role_name):
    """
    For a request made in a granted role limited to some menus: an error message unless the
    endpoint belongs to a given menu, the dashboard or the session/layout endpoints (fail-closed).
    """
    allowed = grant.menu_keys() if grant else None
    if not allowed:
        return None
    rule = request.url_rule.rule if request.url_rule is not None else request.path
    endpoint = f'{request.method} {rule}'
    if endpoint in allowed_api(role_name, allowed) or rule.startswith(SESSION_PREFIXES):
        return None
    log.warning(f"Role access: grant {grant.grant_id} ({role_name}, menus={allowed}) refused {endpoint}")
    return 'This page is not part of your access for this role.'
